#!/usr/bin/env python3
"""Rasterize design/icons/*.svg into LVGL A8 masks (shared/display/th_icons.c).

The masks are tinted at runtime with image recolor, so one mask serves every
theme. Rasterization uses a headless Chromium browser (Microsoft Edge or
Chrome, located automatically or via --browser) so no Python packages are
needed; --check only verifies the source and output digests with stdlib.
"""
import argparse
import base64
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = sorted((ROOT / 'design/icons').glob('*.svg'))
OUT_C = ROOT / 'shared/display/th_icons.c'
OUT_H = ROOT / 'LVGL/include/icons.hpp'
SIZES = (24, 40)
# Device screens are viewed from further away than the portal; slightly
# heavier strokes keep 24 px icons legible on a 2.8-inch panel.
STROKE = '2.1'


def digest():
    h = hashlib.sha256(f'sizes={SIZES};stroke={STROKE}\0'.encode())
    for p in SOURCES:
        h.update(p.name.encode() + b'\0' + p.read_bytes().replace(b'\r\n', b'\n'))
    return h.hexdigest()


def ident(stem):
    return re.sub(r'[^a-z0-9]', '_', stem)


def browser(explicit):
    candidates = [explicit] if explicit else [
        r'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe',
        r'C:\Program Files\Microsoft\Edge\Application\msedge.exe',
        r'C:\Program Files\Google\Chrome\Application\chrome.exe',
        shutil.which('chromium'), shutil.which('google-chrome'), shutil.which('microsoft-edge')]
    for c in candidates:
        if c and Path(c).exists():
            return c
    raise SystemExit('No Chromium browser found; pass --browser')


def rasterize(exe):
    icons = {}
    for p in SOURCES:
        svg = re.sub(r'stroke-width="[^"]+"', f'stroke-width="{STROKE}"', p.read_text())
        icons[p.stem] = 'data:image/svg+xml;base64,' + base64.b64encode(svg.encode()).decode()
    page = '''<!doctype html><body><pre id="out"></pre><script>
const icons = %s, sizes = %s, result = {};
Promise.all(Object.entries(icons).map(([k, src]) => new Promise(ok => {
  const img = new Image(); img.onload = () => { result[k] = {};
    for (const s of sizes) { const c = document.createElement('canvas'); c.width = c.height = s;
      const g = c.getContext('2d'); g.drawImage(img, 0, 0, s, s);
      const d = g.getImageData(0, 0, s, s).data, a = [];
      for (let i = 3; i < d.length; i += 4) a.push(d[i]);
      result[k][s] = a; }
    ok(); }; img.src = src; }))).then(() => { out.textContent = JSON.stringify(result); });
</script></body>''' % (json.dumps(icons), json.dumps(list(SIZES)))
    with tempfile.TemporaryDirectory() as tmp:
        html = Path(tmp) / 'icons.html'
        html.write_text(page)
        dom = subprocess.run([exe, '--headless', '--disable-gpu', f'--user-data-dir={tmp}/profile',
                              '--virtual-time-budget=10000', '--dump-dom', html.as_uri()],
                             capture_output=True, text=True, check=True).stdout
    match = re.search(r'<pre id="out">(.*?)</pre>', dom, re.S)
    if not match or not match[1]:
        raise SystemExit('Browser produced no icon data')
    return json.loads(match[1])


def generate(exe):
    data = rasterize(exe)
    c = ['// Generated by LVGL/tools/generate_icons.py from design/icons; do not edit.',
         f'// source-sha256: {digest()}', '#include "lvgl.h"', '']
    h = ['#pragma once', '// Generated by LVGL/tools/generate_icons.py; do not edit.',
         '#include "lvgl.h"', 'extern "C" {']
    for p in SOURCES:
        for s in SIZES:
            name = f'th_icon_{ident(p.stem)}_{s}'
            values = data[p.stem][str(s)]
            c.append(f'static const uint8_t {name}_map[{s * s}] = {{')
            c.extend('  ' + ','.join(str(v) for v in values[i:i + s]) + ',' for i in range(0, s * s, s))
            c.append('};')
            c.append(f'const lv_image_dsc_t {name} = {{ .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, '
                     f'.cf = LV_COLOR_FORMAT_A8, .w = {s}, .h = {s}, .stride = {s} }}, '
                     f'.data_size = {s * s}, .data = {name}_map }};')
            h.append(f'extern const lv_image_dsc_t {name};')
    h.append('}')
    text = '\n'.join(c) + '\n'
    text += f'// artifact-sha256: {hashlib.sha256(text.encode()).hexdigest()}\n'
    OUT_C.write_text(text, newline='\n')
    OUT_H.write_text('\n'.join(h) + '\n', newline='\n')
    print(f'Wrote {len(SOURCES)} icons x {len(SIZES)} sizes')


def check():
    text = OUT_C.read_text()
    expected = re.search(r'// artifact-sha256: (\w+)\n', text)
    payload = text[:expected.start()] if expected else ''
    if f'// source-sha256: {digest()}\n' not in text or not expected or \
            hashlib.sha256(payload.encode()).hexdigest() != expected[1]:
        raise SystemExit('Icon masks stale or modified: run LVGL/tools/generate_icons.py')
    print(f'LVGL icon masks current: {len(SOURCES)} icons, sizes {SIZES}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--browser')
    args = parser.parse_args()
    check() if args.check else generate(browser(args.browser))
