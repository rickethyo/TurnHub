#!/usr/bin/env python3
"""Convert checked-in OFL fonts with pinned lv_font_conv. No font downloads."""
from pathlib import Path
import hashlib
import json
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
AREA = ROOT / 'LVGL'
SPECS = [('inter', 16, '32-126'), ('inter', 20, '32-126'),
         ('inter', 32, '32-126'), ('inter', 56, '45,48-58'),
         ('inter', 72, '45,48-58'), ('cinzel', 20, '32-126'),
         ('cinzel', 32, '32-126')]

def generate():
    manifest = {}
    for family, size, char_range in SPECS:
        source = ROOT / f'design/fonts/{family.capitalize()}-Variable.ttf'
        name = f'th_{family}_{size}'
        out = AREA / f'assets/{name}.c'
        # Relative paths keep the converter's generated comments reproducible.
        subprocess.run(['node', 'tools/node_modules/lv_font_conv/lv_font_conv.js',
                        '--font', str(source.relative_to(AREA.parent)).replace('design/', '../design/', 1),
                        '--size', str(size), '--bpp', '4', '--format', 'lvgl',
                        '--range', char_range, '--no-compress', '--no-kerning',
                        '--lv-font-name', name, '-o', f'assets/{name}.c'], cwd=AREA, check=True)
        text = out.read_text()
        # Equal digit advances, as in existing TurnHub device font generation.
        ranges = []
        for part in char_range.split(','):
            ends = [int(x) for x in part.split('-')]
            ranges.extend(range(ends[0], ends[-1] + 1))
        pattern = re.compile(r'\{\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)\}')
        matches = list(pattern.finditer(text))
        digit_ids = [ranges.index(ord(c)) + 1 for c in '0123456789']
        cell = max(int(matches[i][2]) for i in digit_ids)
        for i in reversed(digit_ids):
            m = matches[i]
            vals = list(map(int, m.groups()))
            vals[4] += round((cell - vals[1]) / 32)
            vals[1] = cell
            text = text[:m.start()] + ('{.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}' % tuple(vals)) + text[m.end():]
        text = '// Generated by LVGL/tools/generate_fonts.py. OFL: design/fonts/OFL-%s.txt\n' % family.capitalize() + text
        out.write_text(text.rstrip() + "\n")
        manifest[str(out.relative_to(AREA))] = hashlib.sha256(out.read_bytes()).hexdigest()
        manifest[str(source.relative_to(ROOT))] = hashlib.sha256(source.read_bytes()).hexdigest()
    for tool in ['tools/package-lock.json', 'tools/generate_fonts.py']:
        manifest[tool] = hashlib.sha256((AREA / tool).read_bytes()).hexdigest()
    (AREA / 'assets/fonts.sha256.json').write_text(json.dumps(manifest, indent=2) + '\n')

if '--check' in sys.argv:
    manifest = json.loads((AREA / 'assets/fonts.sha256.json').read_text())
    for name, digest in manifest.items():
        path = ROOT / name if name.startswith('design/') else AREA / name
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            sys.exit(f'Font source/artifact changed: {name}; regenerate fonts')
    print('Font source and artifact digests match')
else:
    generate()
