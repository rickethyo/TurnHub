constexpr uint8_t AVATAR_COUNT = sizeof(AVATARS) / sizeof(AVATARS[0]);

inline bool validPresetAvatar(uint8_t avatar) {
  return avatar >= 1 && avatar <= AVATAR_COUNT;
}
inline const AvatarIcon *presetAvatar(uint8_t avatar) {
  return validPresetAvatar(avatar) ? &AVATARS[avatar - 1] : nullptr;
}
inline bool avatarPixel(const AvatarIcon &icon, uint8_t x, uint8_t y) {
  return x < AVATAR_SIZE && y < AVATAR_SIZE && icon.rows[y][x] == '#';
}
// Draws a preset at (x, y), each icon pixel scale x scale device pixels, in
// `color` (background untouched). Works with Adafruit_GFX and LovyanGFX.
template <typename Gfx, typename Color>
inline void drawAvatar(Gfx &g, uint8_t avatar, int16_t x, int16_t y, Color color, uint8_t scale = 1) {
  const AvatarIcon *icon = presetAvatar(avatar);
  if (icon == nullptr) return;
  for (uint8_t row = 0; row < AVATAR_SIZE; ++row) {
    for (uint8_t col = 0; col < AVATAR_SIZE; ++col) {
      if (avatarPixel(*icon, col, row)) g.fillRect(x + col * scale, y + row * scale, scale, scale, color);
    }
  }
}

